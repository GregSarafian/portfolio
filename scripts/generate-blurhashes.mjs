/**
 * generate-blurhashes.mjs
 * Run once (or after adding new assets) to regenerate src/data/blurhashes.ts.
 *   node scripts/generate-blurhashes.mjs
 */

import { readdir, writeFile, mkdir, rm } from 'fs/promises'
import { join, extname, basename } from 'path'
import { execFile } from 'child_process'
import { promisify } from 'util'
import { fileURLToPath } from 'url'
import sharp from 'sharp'
import { encode } from 'blurhash'
import ffmpegInstaller from '@ffmpeg-installer/ffmpeg'

const execFileAsync = promisify(execFile)

const __dirname   = fileURLToPath(new URL('.', import.meta.url))
const ASSETS_DIR  = join(__dirname, '../src/assets')
const OUTPUT_FILE = join(__dirname, '../src/data/blurhashes.ts')
const TMP_DIR     = join(__dirname, '../.blurhash-tmp')
const FFMPEG      = ffmpegInstaller.path

// Blurhash component counts — 4×3 gives a nice soft gradient for portrait screens
const CX = 4
const CY = 3
// Decode size used at runtime (must match BlurhashCanvas props)
export const DECODE_W = 32
export const DECODE_H = 32

// ─── helpers ────────────────────────────────────────────────────────────────

async function encodeImageFile(filePath) {
  const { data, info } = await sharp(filePath)
    .resize(400, null, { fit: 'inside', withoutEnlargement: true })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true })
  return encode(new Uint8ClampedArray(data.buffer), info.width, info.height, CX, CY)
}

async function encodeVideoFile(videoPath, key) {
  const framePath = join(TMP_DIR, `${key.replace('/', '_')}.png`)
  await execFileAsync(FFMPEG, [
    '-i', videoPath,
    '-vframes', '1',
    '-q:v', '2',
    framePath,
    '-y',
  ])
  return encodeImageFile(framePath)
}

// ─── main ───────────────────────────────────────────────────────────────────

await mkdir(TMP_DIR, { recursive: true })

const ASSET_DIRS = ['locket', 'fetii', 'doordash', 'dive-chat']
const IMAGE_EXTS = new Set(['.png', '.jpg', '.jpeg', '.webp'])
const VIDEO_EXTS = new Set(['.mp4', '.webm', '.mov'])

const hashes = {}

for (const dir of ASSET_DIRS) {
  const dirPath = join(ASSETS_DIR, dir)
  let files
  try {
    files = await readdir(dirPath)
  } catch {
    console.warn(`⚠ Skipping missing dir: ${dirPath}`)
    continue
  }

  for (const filename of files.sort()) {
    const ext  = extname(filename).toLowerCase()
    const stem = basename(filename, extname(filename))
    const key  = `${dir}/${stem}`
    const full = join(dirPath, filename)

    try {
      if (IMAGE_EXTS.has(ext)) {
        hashes[key] = await encodeImageFile(full)
        console.log(`✓ image  ${key}`)
      } else if (VIDEO_EXTS.has(ext)) {
        hashes[key] = await encodeVideoFile(full, key)
        console.log(`✓ video  ${key}`)
      }
    } catch (err) {
      console.error(`✗ ${key}: ${err.message}`)
    }
  }
}

await rm(TMP_DIR, { recursive: true, force: true })

const ts = `// Auto-generated by scripts/generate-blurhashes.mjs — do not edit manually.
// Re-run after adding or replacing assets: node scripts/generate-blurhashes.mjs

export const blurhashes: Record<string, string> = ${JSON.stringify(hashes, null, 2)}
`

await mkdir(join(__dirname, '../src/data'), { recursive: true })
await writeFile(OUTPUT_FILE, ts, 'utf8')
console.log(`\n✓ Wrote ${Object.keys(hashes).length} hashes → src/data/blurhashes.ts`)
