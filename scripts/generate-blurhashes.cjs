/**
 * generate-blurhashes.cjs
 * Run once (or after adding new assets) to regenerate src/data/blurhashes.ts.
 *   node scripts/generate-blurhashes.cjs
 *
 * Requires: jimp, @ffmpeg-installer/ffmpeg (dev deps), blurhash (dep)
 */

'use strict'

const { readdir, writeFile, mkdir, rm } = require('fs/promises')
const { join, extname, basename }        = require('path')
const { execFile }                       = require('child_process')
const { promisify }                      = require('util')
const Jimp                               = require('jimp')
const ffmpegInstaller                    = require('@ffmpeg-installer/ffmpeg')
const FFMPEG                             = ffmpegInstaller.path
const execFileAsync                      = promisify(execFile)

const ASSETS_DIR  = join(__dirname, '../src/assets')
const OUTPUT_FILE = join(__dirname, '../src/data/blurhashes.ts')
const TMP_DIR     = join(__dirname, '../.blurhash-tmp')

const IMAGE_EXTS = new Set(['.png', '.jpg', '.jpeg', '.webp'])
const VIDEO_EXTS = new Set(['.mp4', '.webm', '.mov'])
const ASSET_DIRS = ['locket', 'fetii', 'doordash', 'dive-chat']

// ─── helpers ────────────────────────────────────────────────────────────────

async function encodeImageFile(filePath, encode) {
  const img = await Jimp.read(filePath)
  // Resize to a thumbnail for speed — blurhash doesn't need full resolution
  img.resize(400, Jimp.AUTO)
  const { width, height, data } = img.bitmap
  // Jimp bitmap data is RGBA Buffer — wrap in Uint8ClampedArray for blurhash
  const pixels = new Uint8ClampedArray(data.buffer, data.byteOffset, data.byteLength)
  return encode(pixels, width, height, 4, 3)
}

async function encodeVideoFile(videoPath, key, encode) {
  const framePath = join(TMP_DIR, `${key.replace('/', '_')}.png`)
  await execFileAsync(FFMPEG, [
    '-i', videoPath,
    '-vframes', '1',
    '-q:v', '2',
    framePath,
    '-y',
  ])
  return encodeImageFile(framePath, encode)
}

// ─── main ───────────────────────────────────────────────────────────────────

;(async () => {
  // blurhash is ESM-only; use dynamic import from CJS
  const { encode } = await import('blurhash')

  await mkdir(TMP_DIR, { recursive: true })

  const hashes = {}

  for (const dir of ASSET_DIRS) {
    const dirPath = join(ASSETS_DIR, dir)
    let files
    try {
      files = await readdir(dirPath)
    } catch {
      console.warn(`⚠ Skipping missing dir: ${dirPath}`)
      continue
    }

    for (const filename of files.sort()) {
      const ext  = extname(filename).toLowerCase()
      const stem = basename(filename, extname(filename))
      const key  = `${dir}/${stem}`
      const full = join(dirPath, filename)

      try {
        if (IMAGE_EXTS.has(ext)) {
          hashes[key] = await encodeImageFile(full, encode)
          console.log(`✓ image  ${key}`)
        } else if (VIDEO_EXTS.has(ext)) {
          hashes[key] = await encodeVideoFile(full, key, encode)
          console.log(`✓ video  ${key}`)
        }
      } catch (err) {
        console.error(`✗ ${key}: ${err.message}`)
      }
    }
  }

  await rm(TMP_DIR, { recursive: true, force: true })

  const ts = `// Auto-generated by scripts/generate-blurhashes.cjs — do not edit manually.
// Re-run after adding or replacing assets:
//   node scripts/generate-blurhashes.cjs

export const blurhashes: Record<string, string> = ${JSON.stringify(hashes, null, 2)}
`
  await mkdir(join(__dirname, '../src/data'), { recursive: true })
  await writeFile(OUTPUT_FILE, ts, 'utf8')
  console.log(`\n✓ Wrote ${Object.keys(hashes).length} hashes → src/data/blurhashes.ts`)
})()
